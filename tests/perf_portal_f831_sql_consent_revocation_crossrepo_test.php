<?php
declare(strict_types=1);

// CI ONLY: run AFTER the real Portal F831 PostgreSQL18 lab source executes
// from the pinned Portal checkout and exports a redacted V7 plan review.
// The HMAC remains valid even after consent/session revocation. A second
// Portal SQL check must DENY operations despite that valid signature.
require_once __DIR__.'/../src/Domain/Commercial/PortalF419SignedActivationReviewV7LabVerifier.php';
require_once __DIR__.'/../src/Domain/Commercial/PortalV7SignedPlanAgreementLabVerifier.php';
require_once __DIR__.'/../portal-f831-reference/apps/portal/app/Labs/PerformanceV7Pg18/PortalV7SqlExpressConsentLab.php';

use Imagine\Performance\Commercial\PortalV7SignedPlanAgreementLabVerifier as Verifier;
use App\Labs\PerformanceV7Pg18\PortalV7SqlExpressConsentLab as Consent;

function f831Must(bool $yes,string $why):void {
    if(!$yes)throw new RuntimeException('F831 crossrepo revocation: '.$why);
}
foreach([
 'APP_ENV'=>'testing','PERF_PORTAL_V7_SIGNED_PLAN_LAB'=>'1',
 'PERF_PORTAL_F419_V7_REVIEW_LAB'=>'1',
 'PORTAL_PERF_V7_PG18_IDENTITY_LAB'=>'1',
 'PORTAL_PERF_V7_EXPRESS_CONSENT_LAB'=>'1',
] as $name=>$needed)if(getenv($name)!==$needed){
    throw new RuntimeException('F831 requires CI-only flag '.$name);
}
$path='/tmp/portal-f829-signed-plan-ci.json';
if(!is_file($path)||filesize($path)>65536) {
    throw new RuntimeException('Redacted Portal F831 signed review missing.');
}
$data=json_decode(file_get_contents($path),true,512,JSON_THROW_ON_ERROR);
f831Must(is_array($data) && ($data['source']??null)==='portal_f829_pg18_synthetic_review'
    && ($data['actual_customer_acceptance']??null)===false,
    'cannot treat CI consent event as legally binding customer acceptance');
$wire=$data['signed_plan'];
$expected=$data['expected'];
$tenant=$expected['tenant_id'];
$agreement=$expected['agreement_id'];
$period=$expected['period'];
$terms=$data['terms_sha256'];
$plan=$data['stable_plan_sha256'];
$key=static fn(string $issuer,string $kid):?string=>
    $issuer==='imagine-portal-ci' && $kid==='k_f827_plan_01'
    ?str_repeat('Y',48):null;
$proof=Verifier::verify(
    $wire,$data['activation'],$expected,$data['channels'],$data['planned'],
    $data['review_now_utc'],str_repeat('X',48),$key,
    static fn(string $t,string $a,string $nonce,int $expires):bool=>
        $t===$tenant && $a===$agreement && $expires>0
);
f831Must(($proof['hmac_verified_in_lab']??null)===true &&
    ($proof['billable']??null)===false &&
    ($proof['portal_iam_authenticated']??null)===false,
    'HMAC is intact but confers neither live identity nor payment');

$make=static fn(string $user,string $password):PDO=>new PDO(
    'pgsql:host=127.0.0.1;port=5432;dbname=portal_identity_lab;connect_timeout=3',
    $user,$password,[
        PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE=>PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES=>false,
    ]
);
$admin=$make('postgres',getenv('F66_PG_ADMIN_PASSWORD'));
$reader=$make('portal_v7_lab_reader',getenv('PORTAL_V7_PG_READER_PASSWORD'));
$consent=new Consent($reader);
$bearer='PORTAL-V7-PG18-CI-PRIVATE-SESSION-00000001';
$events=$admin->prepare(
    'SELECT event_revision,state,actor_id,organization_id,plan_sha256,terms_sha256
     FROM public.portal_v7_consent_events_lab
     WHERE tenant_id=:tenant AND agreement_id=:agreement AND period=:period
     ORDER BY event_revision'
);
$events->execute(['tenant'=>$tenant,'agreement'=>$agreement,'period'=>$period]);
$history=$events->fetchAll(PDO::FETCH_ASSOC);
f831Must(count($history)===3 &&
    (int)$history[0]['event_revision']===1 &&
    $history[0]['state']==='synthetic_accepted' &&
    (int)$history[1]['event_revision']===2 &&
    $history[1]['state']==='synthetic_revoked' &&
    (int)$history[2]['event_revision']===3 &&
    $history[2]['state']==='synthetic_accepted',
    'versioned append-only history was generated by Portal SQL session gate');
foreach($history as $item) {
    f831Must($item['actor_id']==='e1111111-1111-4111-8111-111111111111'
        && $item['organization_id']===$expected['organization_ref']
        && $item['plan_sha256']===$plan
        && $item['terms_sha256']===$terms,
        'actor and owner are derived from verified Portal SQL session/agreement');
}
// End of F829 run deliberately revokes the session and increments the
// admin-owned agreement revision to 6. The HMAC stays valid, but consent
// must NEVER be usable by a signed-plan-only Performance caller.
f831Must(!$consent->current(
    $bearer,$tenant,$agreement,$period,$plan,$terms,6,3
), 'Portal logout/revocation invalidates previously accepted signed V7 review');
f831Must(!$consent->current(
    $bearer,$tenant,$agreement,$period,$plan,$terms,1,3
), 'old agreement revision cannot be used despite intact HMAC');
f831Must(!$consent->current(
    $bearer,$tenant,$agreement,$period,$plan,$terms,6,1
), 'historical accepted event cannot revive after later revocation and reacceptance');
f831Must(!$consent->current(
    $bearer,'tenant_foreign_12345678',$agreement,$period,$plan,$terms,6,3
), 'forged tenant cannot reuse revoked credential');
f831Must(!$consent->current(
    'PORTAL-F831-UNISSUED-FAKE-SESSION-00000001',
    $tenant,$agreement,$period,$plan,$terms,6,3
), 'unissued first-party bearer cannot authorize');
f831Must(!$consent->current(
    $bearer,$tenant,$agreement,$period,str_repeat('a',64),$terms,6,3
), 'changed plan must not inherit signed review consent');
f831Must(!$consent->current(
    $bearer,$tenant,$agreement,$period,$plan,str_repeat('b',64),6,3
), 'changed terms must not inherit contract');
foreach(['SELECT','INSERT','UPDATE','DELETE'] as $permission){
    $priv=$reader->query("SELECT has_table_privilege(
        session_user,'public.portal_v7_consent_events_lab','$permission')"
    )->fetchColumn();
    f831Must(!in_array($priv,[true,1,'1','t'],true),
        'SQL test login has no direct '. $permission.' on consent event history');
}
f831Must(Consent::limits()['real_portal_customer_authenticated']===false
    && Consent::limits()['legal_customer_acceptance_proven']===false
    && Consent::limits()['billing_enabled']===false,
    'test path never elevates hypothetical consent to operating permission');
echo "PASS F831 crossrepo: HMAC remains valid but PostgreSQL logout/revocation, latest event and owner revision deny current agreement; synthetic-only acceptance, no Ads/PSP/CRM write.\n";
